/// How a built-in function is implemented (`m2.md` §4.6).
#[derive(Clone, Copy)]
pub enum FnKind {
    /// Depends on the arguments only (the M1 form).
    Pure(BuiltinFn),
    /// Uses the catalog or session (`pg_get_userbyid`, `pg_table_is_visible`,
    /// `format_type`, ...).
    Context(fn(&[Datum], &dyn CatalogReader, &SessionInfo) -> Result<Datum>),
    /// 実行時の情報を使う（`pg_backend_pid`、`pg_sleep`、`pg_isolation_test_session_is_blocked`。`m3.md` §4.9）。
    Runtime(fn(&[Datum], &dyn RuntimeInfo) -> Result<Datum>),
    /// FROM 句でだけ呼べる集合返却関数（`generate_series`。`m4/09-types-functions.md` §10.1）。
    Set(SetFn),
}

/// 集合返却関数の実装。
#[derive(Clone, Copy)]
pub struct SetFn {
    /// 引数（評価済み）から行の生成器を作る。引数に NULL があれば 0 行（strict）。
    pub begin: fn(&[Datum]) -> Result<Box<dyn SetIter>>,
    /// `FROM generate_series(..)` の列名と別名の既定（`generate_series`）。
    pub column_name: &'static str,
}

impl std::fmt::Debug for SetFn {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SetFn")
            .field("column_name", &self.column_name)
            .finish_non_exhaustive()
    }
}

/// `SetFn::begin` が返す行の生成器。
pub trait SetIter {
    /// 次の値。尽きたら `None`。
    fn next(&mut self) -> Result<Option<Datum>>;
}

impl std::fmt::Debug for FnKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            FnKind::Pure(_) => f.write_str("FnKind::Pure(..)"),
            FnKind::Context(_) => f.write_str("FnKind::Context(..)"),
            FnKind::Runtime(_) => f.write_str("FnKind::Runtime(..)"),
            FnKind::Set(s) => write!(f, "FnKind::Set({s:?})"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relkind_and_identity_codes() {
        for (k, c, noun) in [
            (RelKind::Table, 'r', "table"),
            (RelKind::Index, 'i', "index"),
            (RelKind::Sequence, 'S', "sequence"),
        ] {
            assert_eq!(k.code(), c);
            assert_eq!(RelKind::from_code(c), Some(k));
            assert_eq!(k.noun(), noun);
        }
        assert_eq!(RelKind::from_code('v'), None);
        assert_eq!(IdentityKind::from_code('a'), Some(IdentityKind::Always));
        assert_eq!(IdentityKind::ByDefault.code(), 'd');
        assert_eq!(IdentityKind::from_code(' '), None);
    }

    #[test]
    fn index_options_round_trip() {
        let col = |descending, nulls_first| IndexColumn {
            attnum: 1,
            opclass: 0,
            opfamily: 0,
            descending,
            nulls_first,
        };
        let def = IndexDef {
            oid: 1,
            name: "i".into(),
            namespace: 2200,
            table_oid: 2,
            locator: crate::storage::smgr::RelFileLocator {
                spc_oid: 1663,
                db_oid: 5,
                rel_number: crate::storage::smgr::RelFileNumber(1),
            },
            columns: vec![
                col(false, false),
                col(true, false),
                col(false, true),
                col(true, true),
            ],
            unique: false,
            primary: false,
            constraint: None,
        };
        for (i, want) in [0i16, 1, 2, 3].into_iter().enumerate() {
            assert_eq!(def.indoption(i), want);
            let (d, n) = IndexDef::flags_from_indoption(want);
            assert_eq!(
                (d, n),
                (def.columns[i].descending, def.columns[i].nulls_first)
            );
        }
        assert_eq!(def.indoption(9), 0);
        assert!(!def.is_constraint_index());
    }

    #[test]
    fn catalog_reader_defaults_are_empty() {
        let c = fake::FakeCatalog::new("postgres");
        // FakeCatalog が上書きしない既定: 制約なし、集約は静的な表。
        assert!(c.constraint_by_oid(1).unwrap().is_none());
        assert!(!builtin::aggregates_named("count").is_empty());
        assert!(!builtin::AGGREGATES.is_empty());
    }
}
