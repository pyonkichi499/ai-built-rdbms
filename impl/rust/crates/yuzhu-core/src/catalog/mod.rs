/// Source text of a stored expression (DEFAULT). It is parsed and analyzed
/// again every time it is used.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BoundExprSource {
    pub expr_sql: String,
}

/// `pg_attribute.attidentity`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum IdentityKind {
    /// `a`: `GENERATED ALWAYS AS IDENTITY`.
    Always,
    /// `d`: `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault,
}

impl IdentityKind {
    /// The `attidentity` character.
    pub fn code(self) -> char {
        match self {
            IdentityKind::Always => 'a',
            IdentityKind::ByDefault => 'd',
        }
    }

    pub fn from_code(c: char) -> Option<IdentityKind> {
        match c {
            'a' => Some(IdentityKind::Always),
            'd' => Some(IdentityKind::ByDefault),
            _ => None,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ColumnDef {
    pub name: String,
    /// 1-based.
    pub attnum: i16,
    pub ty: SqlType,
    pub not_null: bool,
    pub default: Option<BoundExprSource>,
    /// `attidentity`（M4。`None` = 通常の列）。
    pub identity: Option<IdentityKind>,
}

/// A CHECK constraint, stored as SQL text of its expression.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CheckDef {
    pub name: String,
    pub expr_sql: String,
    /// `NO INHERIT`（`pg_constraint.connoinherit`）。
    pub no_inherit: bool,
}

/// `pg_class.relkind`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum RelKind {
    /// `r`.
    Table,
    /// `i`（M4）。`CatalogReader::table()` は返さない。
    Index,
    /// `S`（M4）。列とヒープを持ち SELECT できる。
    Sequence,
}

impl RelKind {
    /// The `relkind` character: `r` / `i` / `S`.
    pub fn code(self) -> char {
        match self {
            RelKind::Table => 'r',
            RelKind::Index => 'i',
            RelKind::Sequence => 'S',
        }
    }

    pub fn from_code(c: char) -> Option<RelKind> {
        match c {
            'r' => Some(RelKind::Table),
            'i' => Some(RelKind::Index),
            'S' => Some(RelKind::Sequence),
            _ => None,
        }
    }

    /// The noun used in error messages: `table` / `index` / `sequence`.
    pub fn noun(self) -> &'static str {
        match self {
            RelKind::Table => "table",
            RelKind::Index => "index",
            RelKind::Sequence => "sequence",
        }
    }
}

/// `pg_constraint.contype`（M4 は c / p / u だけ）。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ConstraintKind {
    /// `c`.
    Check,
    /// `p`.
    PrimaryKey,
    /// `u`.
    Unique,
}

/// `pg_constraint` の 1 行。`pg_get_constraintdef` と DROP の説明が使う。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ConstraintDef {
    pub oid: Oid,
    pub name: String,
    pub namespace: Oid,
    pub kind: ConstraintKind,
    pub table_oid: Oid,
    /// PRIMARY KEY / UNIQUE の索引（`conindid`）。Check は `None`。
    pub index_oid: Option<Oid>,
    /// `conkey`（attnum の並び）。Check は空。
    pub columns: Vec<i16>,
    /// Check の式（`conbin`。SQL テキスト）。
    pub check_sql: Option<String>,
    /// `connoinherit`（CHECK の `NO INHERIT`）。
    pub no_inherit: bool,
}

/// 索引のキー列 1 つ（INCLUDE・式・部分索引は M4 にない）。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IndexColumn {
    pub attnum: i16,
    pub opclass: Oid,
    pub opfamily: Oid,
    pub descending: bool,
    pub nulls_first: bool,
}

/// PRIMARY KEY / UNIQUE 制約が索引を所有するときの、その制約。
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IndexConstraintRef {
    pub oid: Oid,
    pub name: String,
}

/// A B+Tree index definition (`pg_class` + `pg_index`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IndexDef {
    pub oid: Oid,
    pub name: String,
    pub namespace: Oid,
    pub table_oid: Oid,
    pub locator: RelFileLocator,
    pub columns: Vec<IndexColumn>,
    pub unique: bool,
    pub primary: bool,
    pub constraint: Option<IndexConstraintRef>,
}

impl IndexDef {
    /// PRIMARY KEY / UNIQUE 制約が所有する索引か。
    pub fn is_constraint_index(&self) -> bool {
        self.constraint.is_some()
    }

    /// 列 `i` の `indoption`（bit0 = DESC、bit1 = NULLS FIRST）。範囲外は 0。
    pub fn indoption(&self, i: usize) -> i16 {
        self.columns.get(i).map_or(0, |c| {
            i16::from(c.descending) | (i16::from(c.nulls_first) << 1)
        })
    }

    /// `indoption` から `(descending, nulls_first)` を復元する。
    pub fn flags_from_indoption(v: i16) -> (bool, bool) {
        (v & 1 != 0, v & 2 != 0)
    }
}

/// シーケンスのパラメータ（`pg_sequence`）。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SequenceParams {
    /// int2 / int4 / int8.
    pub type_oid: Oid,
    pub start: i64,
    pub increment: i64,
    pub min: i64,
    pub max: i64,
    pub cache: i64,
    pub cycle: bool,
    /// `OWNED BY`: (表の OID, attnum).
    pub owned_by: Option<(Oid, i16)>,
}

/// An immutable table definition. Shared via `Arc`; DDL replaces the whole
/// `Arc<TableDef>`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TableDef {
    pub oid: Oid,
    /// `pg_class.relnamespace`: 11 = `pg_catalog`, 2200 = `public`.
    pub namespace: Oid,
    pub schema: String,
    pub name: String,
    pub kind: RelKind,
    /// Where the table's main fork lives.
    pub locator: RelFileLocator,
    pub columns: Vec<ColumnDef>,
    pub checks: Vec<CheckDef>,
    /// 索引（OID 昇順）。`kind = Table` のときだけ。
    pub indexes: Vec<Arc<IndexDef>>,
    /// `kind = Sequence` のときだけ。
    pub sequence: Option<SequenceParams>,
    /// IDENTITY 列と暗黙のシーケンスの対応: (attnum, シーケンスの OID)。
    pub identity_seqs: Vec<(i16, Oid)>,
}

impl TableDef {
    /// Tables created by initdb (OID below 16384).
    pub fn is_system_catalog(&self) -> bool {
        self.oid < oid::FIRST_NORMAL_OBJECT_ID
    }

    /// Finds a column by (already case-folded) name.
    pub fn column(&self, name: &str) -> Option<&ColumnDef> {
        self.columns.iter().find(|c| c.name == name)
    }

    /// 0-based index of a column by name.
    pub fn column_index(&self, name: &str) -> Option<usize> {
        self.columns.iter().position(|c| c.name == name)
    }

    /// The PRIMARY KEY index, if any.
    pub fn primary_key(&self) -> Option<&Arc<IndexDef>> {
        self.indexes.iter().find(|i| i.primary)
    }

    pub fn index_by_oid(&self, oid: Oid) -> Option<&Arc<IndexDef>> {
        self.indexes.iter().find(|i| i.oid == oid)
    }

    pub fn index_by_name(&self, name: &str) -> Option<&Arc<IndexDef>> {
        self.indexes.iter().find(|i| i.name == name)
    }
}

