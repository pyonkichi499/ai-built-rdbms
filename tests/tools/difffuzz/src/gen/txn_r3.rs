pub fn extra_stmt(ctx: &mut Ctx) {
    let lists = [SETS, READS, FAILED, RO, DDL, CHAIN];
    let l = lists[ctx.rng.below(lists.len() as u64) as usize];
    ctx.push_pick(l);
}
